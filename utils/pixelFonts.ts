export const BITMAP_FONTS: BitmapFont[] = [PIXEL_FONT_5X7, PIXEL_FONT_3X5];

export function getBitmapFont(id: string): BitmapFont | undefined {
  return BITMAP_FONTS.find((font) => font.id === id);
}

/** 取字形；小写缺失时回退到大写 */
export function getGlyph(font: BitmapFont, char: string): string[] | null {
  const direct = font.glyphs[char];
  if (direct) return direct;
  const upper = font.glyphs[char.toUpperCase()];
  return upper ?? null;
}

export function hasGlyph(font: BitmapFont, char: string): boolean {
  return getGlyph(font, char) !== null;
}

/** 找出当前文档里点阵字体不支持的字符（去重，忽略换行） */
export function findUnsupportedChars(font: BitmapFont, text: string): string[] {
  const missing = new Set<string>();
  for (const char of text.replace(/[\r\n]/g, '')) {
    if (char === ' ') continue;
    if (!hasGlyph(font, char)) missing.add(char);
  }
  return Array.from(missing);
}

/** 单行位图尺寸（位图像素） */
export function measureGlyphLine(font: BitmapFont, line: string): number {
  if (line.length === 0) return 0;
  return line.length * font.glyphWidth + (line.length - 1) * font.spacing;
}
